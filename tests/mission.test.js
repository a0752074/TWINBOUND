import test from 'node:test';
import assert from 'node:assert/strict';
import {LEVELS,buildCraft,G0,C} from '../src/config.js';
import {AU,DAY} from '../src/dynamics.js';
import {configureMission,normalizeMission,designChecks,ScienceOperations,downlinkRate,RADIOS,linkGeometry} from '../src/mission.js';
import {Navigation} from '../src/navigation.js';
import {Flight} from '../src/physics.js';
import {eph,getPlan,advance} from './helpers.js';

const level=LEVELS[0],base=()=>buildCraft({engine:1,hull:1,power:1});
function mockNavigation(distanceAU=1){return {isStar:true,state:[distanceAU,0,0,0,0,0],day:0,startDay:0,stability:100,progress:.6,status:'flying',targetDistance:0};}
function runScience(sc,n,seconds,{energy=200,physicalSecondsPerControlSecond=1}={}){for(let t=0;t<seconds-1e-9;t+=1/30){n.day+=physicalSecondsPerControlSecond/30/DAY;sc.step(1/30,energy);}return sc.report('arrived');}
test('payload and radio add real dry mass and price without changing the flight score multiplier',()=>{
  const b=base(),c=configureMission(b,{},'moon');
  assert.equal(c.dryMass,b.dryMass+c.mission.instrument.mass+c.mission.radio.mass);
  assert.equal(c.price,b.price+c.mission.instrument.price+c.mission.radio.price);
  assert.equal(c.multiplier,b.multiplier);assert.ok(designChecks(c,6).every(x=>x.pass));
  const dv=x=>x.engine.isp*G0*Math.log((x.dryMass+x.maxFuel)/x.dryMass);
  assert.ok(dv(c)<dv(b));
});
test('oversize and overbudget designs are reported; a dedicated service and expanded cap resolve them',()=>{
  const heavy=buildCraft({engine:2,hull:2,power:2}),bad=configureMission(heavy,{instrument:'spectrometer'},'moon');
  assert.equal(designChecks(bad).find(x=>x.id==='mass').pass,false);
  assert.equal(designChecks(bad).find(x=>x.id==='budget').pass,false);
  const good=configureMission(heavy,{objective:'composition',instrument:'spectrometer',launcher:'dedicated',budget:'expanded'},'moon');
  assert.ok(designChecks(good).every(x=>x.pass));
});
test('an incompatible instrument can return bytes but cannot complete the selected science goal',()=>{
  const c=configureMission(base(),{objective:'composition',instrument:'camera'},'moon'),n=mockNavigation(.001),s=new ScienceOperations(level,c,n);
  const r=runScience(s,n,60,{physicalSecondsPerControlSecond:100});
  assert.ok(r.generatedMB>6);assert.equal(r.sciencePercent,0);assert.equal(r.complete,false);
  assert.equal(r.checks.find(x=>x.id==='instrument').pass,false);
});
test('stored, transmitted, and dropped data conserve all generated bytes',()=>{
  const c=configureMission(base(),{instrument:'spectrometer',radio:'compact'},'moon'),n=mockNavigation(30),s=new ScienceOperations(level,c,n);
  const r=runScience(s,n,300);assert.ok(r.droppedMB>0);assert.ok(r.storedMB<=c.mission.instrument.storageMB);
  assert.ok(Math.abs(r.generatedMB-r.storedMB-r.transmittedMB-r.droppedMB)<1e-8);
  assert.ok(Math.abs(r.transmittedMB-r.receivedMB-r.inTransitMB)<1e-8);
});
test('transmitted observations cannot be credited on Earth before their one-way light time',()=>{
  const c=configureMission(base(),{},'moon'),n=mockNavigation(1),s=new ScienceOperations(level,c,n);
  runScience(s,n,2);assert.ok(s.transmittedMB>0);assert.equal(s.receivedMB,0);
  assert.ok(Math.abs(s.lightSeconds-AU/(C/1000))<1e-8);
  n.day+=(s.lightSeconds+2)/DAY;s.receive();assert.ok(s.receivedMB>0);
});
test('a solar-system mission requires ground delivery, while the ideal interstellar demonstration uses an onboard archive',()=>{
  const c=configureMission(base(),{},'moon'),n=mockNavigation(1),s=new ScienceOperations(level,c,n);
  runScience(s,n,30);assert.ok(s.report('arrived').sciencePercent>0);
  n.isStar=false;assert.equal(s.report('arrived').sciencePercent,0);
  assert.equal(s.report('arrived').complete,false);
  n.isStar=true;assert.equal(s.report('failed').complete,false);
});
test('a more capable radio changes return rate; the range law is inverse square below the cap',()=>{
  const a=downlinkRate(RADIOS.compact,10*AU),b=downlinkRate(RADIOS.compact,20*AU);
  assert.ok(Math.abs(a/b-4)<1e-10);assert.ok(downlinkRate(RADIOS.dish,30*AU)>downlinkRate(RADIOS.compact,30*AU));
  assert.equal(downlinkRate(RADIOS.dish,.001*AU),RADIOS.dish.maxMBps);
  assert.equal(downlinkRate(RADIOS.dish,AU,true),0);
});
test('science and radio power consume the existing battery, and no energy means no new data',()=>{
  const c=configureMission(base(),{},'moon'),n=mockNavigation(.001),s=new ScienceOperations(level,c,n);
  runScience(s,n,10);assert.ok(s.powerWh>0);const bytes=s.generatedMB;runScience(s,n,10,{energy:0});assert.equal(s.generatedMB,bytes);
  const plan=getPlan('moon'),nav=new Navigation(level,plan,eph,c),f=new Flight(level,c,1,nav);
  nav.targetDistance=0;f.objects=[];f.nextSpawn=f.nextSupply=f.nextComet=Infinity;
  const e=f.energy;advance(f,1);assert.ok(e-f.energy>(1800-c.power.generation)/3600);
});
test('Earth distance and solar occultation come from actual physical positions',()=>{
  const n={isStar:false,day:0,state:[-1,0,0,0,0,0],ephem:{body:name=>({r:name==='earth'?[1,0,0]:[0,0,0]})}};
  let g=linkGeometry(n);assert.equal(g.distanceKm,2*AU);assert.equal(g.blocked,true);
  n.state=[1,1,0,0,0,0];g=linkGeometry(n);assert.equal(g.distanceKm,AU);assert.equal(g.blocked,false);
  const c=configureMission(base(),{},'moon'),real=new Navigation(level,getPlan('moon'),eph,c);
  const earth=eph.body('earth',real.day).r,expected=Math.hypot(...real.state.slice(0,3).map((x,i)=>x-earth[i]))*AU;
  assert.ok(Math.abs(linkGeometry(real).distanceKm-expected)<1e-7);
});
test('malformed and cross-scenario mission settings fall back to valid choices',()=>{
  assert.equal(normalizeMission({objective:'clocks',radio:'__proto__'},'moon').objective,'imaging');
  assert.equal(normalizeMission({radio:'__proto__'},'moon').radio,'dish');
  assert.equal(normalizeMission({},'proxima').instrument,'clock');
  assert.equal(designChecks(configureMission(base(),{},'moon'),21).find(c=>c.id==='lifetime').pass,false);
});
for(const destination of LEVELS)test(`configured science mission reaches ${destination.id} on the event date`,()=>{
  const c=configureMission(buildCraft({engine:2,hull:2,power:2}),{launcher:'dedicated',budget:'expanded'},destination.id);
  const plan=getPlan(destination.id,'2026-11-14'),f=new Flight(destination,c,12,new Navigation(destination,plan,eph,c));
  f.objects=[];f.nextSpawn=f.nextSupply=f.nextComet=f.nextHole=Infinity;
  advance(f,1000);const r=f.snapshot();
  assert.equal(r.status,'arrived');assert.equal(r.science.complete,true);assert.ok(r.score>0);
  if(destination.id==='proxima')assert.ok(r.science.generatedMB>=r.science.requiredMB);
  else{assert.ok(r.science.receivedMB>=r.science.requiredMB);assert.ok(r.navigation.targetKm<=destination.near);}
});
